export type StarterKind = keyof typeof starterCategories

export function starterCategoryName(kind: StarterKind, description: string) {
  const normalized = description.trim().toLowerCase()
  return starterCategories[kind].find(
    ({ name }) => name.slice(name.indexOf(' ') + 1).toLowerCase() === normalized,
  )?.name
}

export function normalizeBuiltInWord(description: string) {
  return description
    .trim()
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replace(builtInWordWhitespacePattern, ' ')
}

function indexBuiltInWords(kind: StarterKind) {
  return new Map(
    starterCategories[kind].flatMap((group) =>
      group.words.map((word) => [normalizeBuiltInWord(word), group] as const),
    ),
  )
}

const builtInGroupsByWord = {
  expense: indexBuiltInWords('expense'),
  income: indexBuiltInWords('income'),
}

export function builtInGroup(kind: StarterKind, description: string) {
  return builtInGroupsByWord[kind].get(normalizeBuiltInWord(description))
}
